/* Qwen 的一个注意力头包含 128 个元素。沿用原项目的 int8 解码与向量乘法，
 * 一次调用计算完整的 128 维点积。每轮将 64 维 Q 保存在寄存器中，遍历历史 K；
 * 第二轮将另外 64 维的点积加到同一份 scores。scale 由调用者随后应用。
 * query 和每行 keys 的起始地址必须位于 16 字节边界，count 至少为 1。 */
void attention_scores_vfpu_128(const float *query, const int8_t *keys, int stride,
                                int count, float *scores) {
    const float *q = query;
    const int8_t *key_half = keys, *k;
    float *s;
    int n, half = 0;
    __asm__ volatile (
        ".set push\n"
        ".set reorder\n"
        ".set macro\n"
        "1:\n"
        "move %[k], %[base]\n"
        "move %[s], %[scores]\n"
        "move %[n], %[count]\n"
        "lv.q C400, 0(%[q])\n"
        "lv.q C410, 16(%[q])\n"
        "lv.q C420, 32(%[q])\n"
        "lv.q C430, 48(%[q])\n"
        "lv.q C500, 64(%[q])\n"
        "lv.q C510, 80(%[q])\n"
        "lv.q C520, 96(%[q])\n"
        "lv.q C530, 112(%[q])\n"
        "lv.q C600, 128(%[q])\n"
        "lv.q C610, 144(%[q])\n"
        "lv.q C620, 160(%[q])\n"
        "lv.q C630, 176(%[q])\n"
        "lv.q C700, 192(%[q])\n"
        "lv.q C710, 208(%[q])\n"
        "lv.q C720, 224(%[q])\n"
        "lv.q C730, 240(%[q])\n"
        "2:\n"
        "lv.q C100, 0(%[k])\n"
        "lv.q C110, 16(%[k])\n"
        "lv.q C120, 32(%[k])\n"
        "lv.q C130, 48(%[k])\n"
        /* vc2i 按有符号字节展开，vi2f 的 24 抵消展开时的位移。 */
        "vc2i.s C200, S100\n"
        "vc2i.s C210, S101\n"
        "vc2i.s C220, S102\n"
        "vc2i.s C230, S103\n"
        "vc2i.s C300, S110\n"
        "vc2i.s C310, S111\n"
        "vc2i.s C320, S112\n"
        "vc2i.s C330, S113\n"
        "vi2f.q C200, C200, 24\n"
        "vi2f.q C210, C210, 24\n"
        "vi2f.q C220, C220, 24\n"
        "vi2f.q C230, C230, 24\n"
        "vi2f.q C300, C300, 24\n"
        "vi2f.q C310, C310, 24\n"
        "vi2f.q C320, C320, 24\n"
        "vi2f.q C330, C330, 24\n"
        "vmul.q C200, C200, C400\n"
        "vmul.q C210, C210, C410\n"
        "vmul.q C220, C220, C420\n"
        "vmul.q C230, C230, C430\n"
        "vmul.q C300, C300, C500\n"
        "vmul.q C310, C310, C510\n"
        "vmul.q C320, C320, C520\n"
        "vmul.q C330, C330, C530\n"
        "vadd.q C200, C200, C210\n"
        "vadd.q C220, C220, C230\n"
        "vadd.q C300, C300, C310\n"
        "vadd.q C320, C320, C330\n"
        "vadd.q C200, C200, C220\n"
        "vadd.q C300, C300, C320\n"
        "vadd.q C000, C200, C300\n"
        "vc2i.s C200, S120\n"
        "vc2i.s C210, S121\n"
        "vc2i.s C220, S122\n"
        "vc2i.s C230, S123\n"
        "vc2i.s C300, S130\n"
        "vc2i.s C310, S131\n"
        "vc2i.s C320, S132\n"
        "vc2i.s C330, S133\n"
        "vi2f.q C200, C200, 24\n"
        "vi2f.q C210, C210, 24\n"
        "vi2f.q C220, C220, 24\n"
        "vi2f.q C230, C230, 24\n"
        "vi2f.q C300, C300, 24\n"
        "vi2f.q C310, C310, 24\n"
        "vi2f.q C320, C320, 24\n"
        "vi2f.q C330, C330, 24\n"
        "vmul.q C200, C200, C600\n"
        "vmul.q C210, C210, C610\n"
        "vmul.q C220, C220, C620\n"
        "vmul.q C230, C230, C630\n"
        "vmul.q C300, C300, C700\n"
        "vmul.q C310, C310, C710\n"
        "vmul.q C320, C320, C720\n"
        "vmul.q C330, C330, C730\n"
        "vadd.q C200, C200, C210\n"
        "vadd.q C220, C220, C230\n"
        "vadd.q C300, C300, C310\n"
        "vadd.q C320, C320, C330\n"
        "vadd.q C200, C200, C220\n"
        "vadd.q C300, C300, C320\n"
        "vadd.q C200, C200, C300\n"
        "vadd.q C000, C000, C200\n"
        "vfad.q S010, C000\n"
        /* 第一轮直接写入，第二轮加上前一轮的分数。 */
        "beqz %[half], 3f\n"
        "lv.s S011, 0(%[s])\n"
        "vadd.s S010, S010, S011\n"
        "3:\n"
        "sv.s S010, 0(%[s])\n"
        "addu %[k], %[k], %[stride]\n"
        "addiu %[s], %[s], 4\n"
        "addiu %[n], %[n], -1\n"
        "bnez %[n], 2b\n"
        "addiu %[q], %[q], 256\n"
        "addiu %[base], %[base], 64\n"
        "addiu %[half], %[half], 1\n"
        "slti %[n], %[half], 2\n"
        "bnez %[n], 1b\n"
        ".set pop\n"
        : [q] "+&r"(q), [base] "+&r"(key_half), [half] "+&r"(half),
          [k] "=&r"(k), [s] "=&r"(s), [n] "=&r"(n)
        : [scores] "r"(scores), [count] "r"(count), [stride] "r"(stride)
        : "memory");
}

/* 一次调用写入完整的 128 维输出。每轮保持 64 个累加结果，
 * 遍历所有历史 V 后写入对应的输出位置，共执行两轮。
 * weights 已包含 Softmax 权重与每个历史位置的 V scale。 */
void attention_accum_vfpu_128(float *output, const int8_t *values, int stride,
                               int count, const float *weights) {
    float *out = output;
    const int8_t *value_half = values, *v;
    const float *w;
    int n, halves = 2;
    __asm__ volatile (
        ".set push\n"
        ".set reorder\n"
        ".set macro\n"
        "1:\n"
        "move %[v], %[base]\n"
        "move %[w], %[weights]\n"
        "move %[n], %[count]\n"
        "vzero.q C400\n"
        "vzero.q C410\n"
        "vzero.q C420\n"
        "vzero.q C430\n"
        "vzero.q C500\n"
        "vzero.q C510\n"
        "vzero.q C520\n"
        "vzero.q C530\n"
        "vzero.q C600\n"
        "vzero.q C610\n"
        "vzero.q C620\n"
        "vzero.q C630\n"
        "vzero.q C700\n"
        "vzero.q C710\n"
        "vzero.q C720\n"
        "vzero.q C730\n"
        "2:\n"
        "lv.s S001, 0(%[w])\n"
        "lv.q C100, 0(%[v])\n"
        "lv.q C110, 16(%[v])\n"
        "lv.q C120, 32(%[v])\n"
        "lv.q C130, 48(%[v])\n"
        "vc2i.s C200, S100\n"
        "vc2i.s C210, S101\n"
        "vc2i.s C220, S102\n"
        "vc2i.s C230, S103\n"
        "vc2i.s C300, S110\n"
        "vc2i.s C310, S111\n"
        "vc2i.s C320, S112\n"
        "vc2i.s C330, S113\n"
        "vi2f.q C200, C200, 24\n"
        "vi2f.q C210, C210, 24\n"
        "vi2f.q C220, C220, 24\n"
        "vi2f.q C230, C230, 24\n"
        "vi2f.q C300, C300, 24\n"
        "vi2f.q C310, C310, 24\n"
        "vi2f.q C320, C320, 24\n"
        "vi2f.q C330, C330, 24\n"
        "vscl.q C200, C200, S001\n"
        "vscl.q C210, C210, S001\n"
        "vscl.q C220, C220, S001\n"
        "vscl.q C230, C230, S001\n"
        "vscl.q C300, C300, S001\n"
        "vscl.q C310, C310, S001\n"
        "vscl.q C320, C320, S001\n"
        "vscl.q C330, C330, S001\n"
        "vadd.q C400, C400, C200\n"
        "vadd.q C410, C410, C210\n"
        "vadd.q C420, C420, C220\n"
        "vadd.q C430, C430, C230\n"
        "vadd.q C500, C500, C300\n"
        "vadd.q C510, C510, C310\n"
        "vadd.q C520, C520, C320\n"
        "vadd.q C530, C530, C330\n"
        "vc2i.s C200, S120\n"
        "vc2i.s C210, S121\n"
        "vc2i.s C220, S122\n"
        "vc2i.s C230, S123\n"
        "vc2i.s C300, S130\n"
        "vc2i.s C310, S131\n"
        "vc2i.s C320, S132\n"
        "vc2i.s C330, S133\n"
        "vi2f.q C200, C200, 24\n"
        "vi2f.q C210, C210, 24\n"
        "vi2f.q C220, C220, 24\n"
        "vi2f.q C230, C230, 24\n"
        "vi2f.q C300, C300, 24\n"
        "vi2f.q C310, C310, 24\n"
        "vi2f.q C320, C320, 24\n"
        "vi2f.q C330, C330, 24\n"
        "vscl.q C200, C200, S001\n"
        "vscl.q C210, C210, S001\n"
        "vscl.q C220, C220, S001\n"
        "vscl.q C230, C230, S001\n"
        "vscl.q C300, C300, S001\n"
        "vscl.q C310, C310, S001\n"
        "vscl.q C320, C320, S001\n"
        "vscl.q C330, C330, S001\n"
        "vadd.q C600, C600, C200\n"
        "vadd.q C610, C610, C210\n"
        "vadd.q C620, C620, C220\n"
        "vadd.q C630, C630, C230\n"
        "vadd.q C700, C700, C300\n"
        "vadd.q C710, C710, C310\n"
        "vadd.q C720, C720, C320\n"
        "vadd.q C730, C730, C330\n"
        "addu %[v], %[v], %[stride]\n"
        "addiu %[w], %[w], 4\n"
        "addiu %[n], %[n], -1\n"
        "bnez %[n], 2b\n"
        "sv.q C400, 0(%[out])\n"
        "sv.q C410, 16(%[out])\n"
        "sv.q C420, 32(%[out])\n"
        "sv.q C430, 48(%[out])\n"
        "sv.q C500, 64(%[out])\n"
        "sv.q C510, 80(%[out])\n"
        "sv.q C520, 96(%[out])\n"
        "sv.q C530, 112(%[out])\n"
        "sv.q C600, 128(%[out])\n"
        "sv.q C610, 144(%[out])\n"
        "sv.q C620, 160(%[out])\n"
        "sv.q C630, 176(%[out])\n"
        "sv.q C700, 192(%[out])\n"
        "sv.q C710, 208(%[out])\n"
        "sv.q C720, 224(%[out])\n"
        "sv.q C730, 240(%[out])\n"
        "addiu %[out], %[out], 256\n"
        "addiu %[base], %[base], 64\n"
        "addiu %[halves], %[halves], -1\n"
        "bnez %[halves], 1b\n"
        ".set pop\n"
        : [out] "+&r"(out), [base] "+&r"(value_half), [halves] "+&r"(halves),
          [v] "=&r"(v), [w] "=&r"(w), [n] "=&r"(n)
        : [weights] "r"(weights), [count] "r"(count), [stride] "r"(stride)
        : "memory");
}
